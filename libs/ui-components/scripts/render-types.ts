interface CemField {
  kind: string;
  name: string;
  privacy?: string;
  static?: boolean;
  readonly?: boolean;
  type?: { text: string };
  description?: string;
}
interface CemEvent {
  name: string;
  type?: { text: string };
  description?: string;
}
interface CemDeclaration {
  kind: string;
  name: string;
  tagName?: string;
  members?: CemField[];
  events?: CemEvent[];
  description?: string;
}
interface CemManifest {
  modules: { declarations?: CemDeclaration[] }[];
}

const HEADER = '// GENERATED by `nx run ui-components:manifest` from custom-elements.json. Do not edit.\n';

const pascal = (tag: string) => tag.replace(/(^|-)([a-z])/g, (_, __, c: string) => c.toUpperCase());

function eventType(e: CemEvent): string {
  const fromDescription = /CustomEvent<([A-Za-z0-9_]+)>/.exec(e.description ?? '')?.[1];
  if (fromDescription) return `CustomEvent<${fromDescription}>`;
  return e.type?.text === 'CustomEvent' ? 'CustomEvent<void>' : 'Event';
}

export function renderTypes(manifest: CemManifest, typesSource: string): Record<string, string> {
  const exported = new Set([...typesSource.matchAll(/export type \{([^}]+)\}/g)].flatMap((m) => (m[1] ?? '').split(',').map((s) => s.trim()).filter(Boolean)));
  const elements = manifest.modules
    .flatMap((m) => m.declarations ?? [])
    .filter((d): d is CemDeclaration & { tagName: string } => d.kind === 'class' && !!d.tagName)
    .sort((a, b) => a.tagName.localeCompare(b.tagName));

  const used = new Set<string>();
  const noteTypes = (text: string) => {
    for (const id of text.match(/[A-Z][A-Za-z0-9_]*/g) ?? []) if (exported.has(id)) used.add(id);
  };

  const propBlocks: string[] = [];
  const eventBlocks: string[] = [];
  for (const el of elements) {
    const name = pascal(el.tagName);
    const fields = (el.members ?? []).filter(
      (m) => m.kind === 'field' && !m.static && m.privacy !== 'private' && m.privacy !== 'protected' && !m.readonly,
    );
    const props = fields.map((f) => {
      const type = (f.type?.text ?? 'unknown').replace(/\s*\|\s*undefined$/, '');
      noteTypes(type);
      return `  ${f.name}?: ${type};`;
    });
    propBlocks.push(`/** <${el.tagName}> properties. */\nexport interface ${name}Props {\n${props.join('\n')}\n}`);
    const events = (el.events ?? []).map((e) => {
      const t = eventType(e);
      noteTypes(t);
      return `  '${e.name}': ${t};`;
    });
    eventBlocks.push(`/** <${el.tagName}> events. */\nexport interface ${name}Events {\n${events.join('\n')}\n}`);
  }

  const imports = used.size ? `import type { ${[...used].sort().join(', ')} } from '../src/types';\n\n` : '';
  const elementsDts =
    HEADER +
    imports +
    propBlocks.join('\n\n') +
    '\n\n' +
    eventBlocks.join('\n\n') +
    `\n\nexport interface BfElementProps {\n${elements.map((e) => `  '${e.tagName}': ${pascal(e.tagName)}Props;`).join('\n')}\n}\n` +
    `\nexport interface BfElementEvents {\n${elements.map((e) => `  '${e.tagName}': ${pascal(e.tagName)}Events;`).join('\n')}\n}\n`;

  const allEvents = elements.flatMap((e) => (e.events ?? []).map((ev) => ({ tag: e.tagName, ev })));
  const domDts =
    HEADER +
    `import type { BfElementEvents, BfElementProps } from './elements';\n\n` +
    `declare global {\n  interface HTMLElementTagNameMap {\n${elements
      .map((e) => `    '${e.tagName}': HTMLElement & BfElementProps['${e.tagName}'];`)
      .join('\n')}\n  }\n  interface HTMLElementEventMap {\n${allEvents
      .map(({ tag, ev }) => `    '${ev.name}': BfElementEvents['${tag}']['${ev.name}'];`)
      .join('\n')}\n  }\n}\n\nexport {};\n`;

  const reactDts =
    HEADER +
    `import type { DetailedHTMLProps, HTMLAttributes } from 'react';\nimport type { BfElementEvents, BfElementProps } from './elements';\n\n` +
    `type Base = DetailedHTMLProps<HTMLAttributes<HTMLElement>, HTMLElement> & { class?: string };\n` +
    `/** React 19 attaches listeners for custom-element props named \`on<event-name>\`. */\n` +
    `type ReactEvents<E> = { [K in keyof E as \`on\${K & string}\`]?: (event: E[K]) => void };\n\n` +
    `declare module 'react' {\n  namespace JSX {\n    interface IntrinsicElements {\n${elements
      .map(
        (e) =>
          `      '${e.tagName}': Base & BfElementProps['${e.tagName}'] & ReactEvents<BfElementEvents['${e.tagName}']>;`,
      )
      .join('\n')}\n    }\n  }\n}\n\nexport {};\n`;

  const vueDts =
    HEADER +
    `import type { DefineComponent } from 'vue';\nimport type { BfElementEvents, BfElementProps } from './elements';\n\n` +
    `/** Vue compiles \`@bf-toggle\` to the prop \`onBfToggle\`. */\n` +
    `type Camel<S extends string> = S extends \`\${infer H}-\${infer T}\` ? \`\${Capitalize<H>}\${Camel<T>}\` : Capitalize<S>;\n` +
    `type VueEvents<E> = { [K in keyof E as \`on\${Camel<K & string>}\`]?: (event: E[K]) => void };\n` +
    `type El<T extends keyof BfElementProps> = DefineComponent<BfElementProps[T] & VueEvents<BfElementEvents[T]> & { class?: unknown; slot?: string }>;\n\n` +
    `declare module 'vue' {\n  interface GlobalComponents {\n${elements
      .map((e) => `    '${e.tagName}': El<'${e.tagName}'>;`)
      .join('\n')}\n  }\n  /** Native \`slot\` attribute, needed to place content into bf-* (web component) slots. */\n  interface HTMLAttributes {\n    slot?: string;\n  }\n}\n\nexport {};\n`;

  return { 'elements.d.ts': elementsDts, 'dom.d.ts': domDts, 'react.d.ts': reactDts, 'vue.d.ts': vueDts };
}
