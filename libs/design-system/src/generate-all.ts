import { baseCss, modesCss, themeCss } from './generate';
import { propertyRegistrations } from './properties';

const HEADER = '/* GENERATED by `nx run design-system:generate` from src/tokens.ts. Do not edit. */\n';

/**
 * Page-level stylesheet loaded once by the shell (never inside a shadow root):
 * self-hosted fonts, mode variables, and the `@property` registrations
 * Tailwind utilities need, which browsers ignore inside shadow roots.
 */
export async function documentCss(): Promise<string> {
  const properties = await propertyRegistrations(themeCss());
  return (
    HEADER +
    `@import '@fontsource-variable/inter/wght.css';
@import '@fontsource-variable/space-grotesk/wght.css';
@import '@fontsource-variable/jetbrains-mono/wght.css';
@import './modes.css';

/* Registered custom properties used by Tailwind utilities (shadows, rings, transforms, gradients, filters, ...). */
${properties}
`
  );
}

export async function generateAll(): Promise<Record<string, string>> {
  return {
    'theme.css': themeCss(),
    'modes.css': modesCss(),
    'base.css': baseCss(),
    'document.css': await documentCss(),
  };
}
