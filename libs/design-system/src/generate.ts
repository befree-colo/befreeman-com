import {
  animations,
  breakpoints,
  colorRoles,
  colors,
  durations,
  easings,
  fonts,
  radius,
  shadows,
  spacing,
  typeScale,
} from './tokens';
import type { Mode } from './tokens';

const HEADER = '/* GENERATED by `nx run design-system:generate` from src/tokens.ts. Do not edit. */\n';

const modeVars = (mode: Mode, indent = '  ') =>
  colorRoles.map((role) => `${indent}--bf-${role}: ${colors[mode][role]};`).join('\n');

/** Tailwind v4 theme: utilities map to semantic variables, so modes switch without `dark:` variants. */
export function themeCss(): string {
  const lines: string[] = [];
  lines.push('@theme inline {');
  lines.push('  --color-*: initial;');
  lines.push('  --color-transparent: transparent;');
  lines.push('  --color-current: currentColor;');
  lines.push('  --color-white: #ffffff;');
  lines.push('  --color-black: #000000;');
  for (const role of colorRoles) lines.push(`  --color-${role}: var(--bf-${role});`);
  lines.push('}');
  lines.push('');
  lines.push('@theme {');
  lines.push(`  --font-display: ${fonts.display};`);
  lines.push(`  --font-sans: ${fonts.sans};`);
  lines.push(`  --font-mono: ${fonts.mono};`);
  lines.push(`  --spacing: ${spacing};`);
  for (const [name, [size, lh]] of Object.entries(typeScale)) {
    lines.push(`  --text-${name}: ${size};`);
    lines.push(`  --text-${name}--line-height: ${lh};`);
  }
  lines.push('  --radius-*: initial;');
  for (const [name, value] of Object.entries(radius)) lines.push(`  --radius-${name}: ${value};`);
  lines.push('  --shadow-*: initial;');
  for (const [name, value] of Object.entries(shadows)) lines.push(`  --shadow-${name}: ${value};`);
  lines.push('  --breakpoint-*: initial;');
  for (const [name, value] of Object.entries(breakpoints)) lines.push(`  --breakpoint-${name}: ${value};`);
  lines.push('  --ease-*: initial;');
  for (const [name, value] of Object.entries(easings)) lines.push(`  --ease-${name}: ${value};`);
  lines.push('  --animate-*: initial;');
  for (const [name, a] of Object.entries(animations)) lines.push(`  --animate-${name}: ${a.value};`);
  for (const [name, a] of Object.entries(animations)) {
    lines.push('');
    lines.push(`  @keyframes bf-${name} {`);
    lines.push(`    ${a.keyframes}`);
    lines.push('  }');
  }
  lines.push('}');
  return HEADER + lines.join('\n') + '\n';
}

/** Duration variables, zeroed under reduced motion. */
function motionVars(reduced: boolean, indent = '  '): string {
  return Object.entries(durations)
    .map(([name, ms]) => `${indent}--bf-duration-${name}: ${reduced ? 0 : ms}ms;`)
    .join('\n');
}

/** Semantic color values per mode, keyed off `data-theme` on <html>. Custom properties inherit into shadow roots. */
export function modesCss(): string {
  return (
    HEADER +
    `:root,
:root[data-theme='light'] {
  color-scheme: light;
${modeVars('light')}
${motionVars(false)}
}

:root[data-theme='dark'] {
  color-scheme: dark;
${modeVars('dark')}
}

/* No stored choice and no script yet: follow the system. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
    color-scheme: dark;
${modeVars('dark', '    ')}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
${motionVars(true, '    ')}
  }
}
`
  );
}

/** Element defaults layered on top of Tailwind preflight. Included in every shadow sheet. */
export function baseCss(): string {
  return (
    HEADER +
    `@layer base {
  :host,
  html {
    font-family: var(--font-sans);
    color: var(--bf-ink);
    background-color: var(--bf-surface);
    -webkit-font-smoothing: antialiased;
    text-rendering: optimizeLegibility;
  }

  h1,
  h2,
  h3,
  h4 {
    font-family: var(--font-display);
    letter-spacing: -0.02em;
    text-wrap: balance;
  }

  p {
    text-wrap: pretty;
  }

  a {
    color: var(--bf-accent);
    text-underline-offset: 0.2em;
  }

  :focus-visible {
    outline: 3px solid var(--bf-focus);
    outline-offset: 3px;
    border-radius: 0.25rem;
  }

  ::selection {
    background-color: color-mix(in oklab, var(--bf-accent) 35%, transparent);
  }

  [hidden] {
    display: none !important;
  }
}

/* Reduced motion: no transitions, no animations, no smooth scrolling. */
@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation: none !important;
    transition-duration: 0ms !important;
    scroll-behavior: auto !important;
  }
}
`
  );
}
